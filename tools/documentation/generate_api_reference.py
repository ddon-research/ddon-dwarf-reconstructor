"""Generate the source-derived Python API declaration pages.

The generator deliberately uses only the standard library.  It discovers source files and writes
the Markdown directives consumed by Zensical's preliminary mkdocstrings integration; it never
imports the application package or renders HTML.
"""

from __future__ import annotations

import argparse
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
SOURCE_ROOT = REPOSITORY_ROOT / "src" / "ddon_dwarf_reconstructor"
OUTPUT_ROOT = REPOSITORY_ROOT / "docs" / "api" / "generated"
GROUPS = ("root", "application", "core", "domain", "infrastructure", "utilities")
GROUP_SOURCE_DIRS = {
    "application": "application",
    "core": "core",
    "domain": "domain",
    "infrastructure": "infrastructure",
    "utilities": "utils",
}
GROUP_TITLES = {
    "root": "Root modules",
    "application": "Application modules",
    "core": "Core modules",
    "domain": "Domain modules",
    "infrastructure": "Infrastructure modules",
    "utilities": "Utility modules",
}
GENERATED_HEADER = "<!-- Generated by tools/documentation/generate_api_reference.py; do not edit. -->"


class DuplicateModuleError(ValueError):
    """Raised when two source paths resolve to the same Python module identifier."""


class UnexpectedSourceGroupError(ValueError):
    """Raised when a source file is outside the fixed API reference groups."""


@dataclass(frozen=True, slots=True)
class ModuleRecord:
    """Describe one discovered source module without importing it."""

    name: str
    group: str
    path: Path


def module_name_for_path(path: Path, source_root: Path) -> str:
    """Convert a source path into its dotted package or module identifier."""
    relative = path.relative_to(source_root)
    if relative.suffix != ".py":
        raise ValueError(f"Expected a Python source file: {path}")

    parts = list(relative.with_suffix("").parts)
    if parts and parts[-1] == "__init__":
        parts.pop()
    return ".".join((source_root.name, *parts))


def group_for_path(path: Path, source_root: Path) -> str:
    """Return the fixed documentation group for a source path."""
    relative = path.relative_to(source_root)
    if len(relative.parts) <= 1:
        return "root"

    source_group = relative.parts[0]
    for group, directory in GROUP_SOURCE_DIRS.items():
        if source_group == directory:
            return group
    raise UnexpectedSourceGroupError(
        f"Source module {path} is outside the supported groups: {', '.join(GROUPS)}"
    )


def _path_sort_key(path: Path, source_root: Path) -> tuple[str, str]:
    relative_name = path.relative_to(source_root).as_posix()
    return relative_name.casefold(), relative_name


def _module_sort_key(module: ModuleRecord) -> tuple[str, str]:
    return module.name.casefold(), module.name


def discover_modules(source_root: Path = SOURCE_ROOT) -> tuple[ModuleRecord, ...]:
    """Discover every Python source file in stable lexical order."""
    paths = sorted(source_root.rglob("*.py"), key=lambda path: _path_sort_key(path, source_root))
    modules: list[ModuleRecord] = []
    seen: dict[str, Path] = {}
    for path in paths:
        name = module_name_for_path(path, source_root)
        previous = seen.get(name)
        if previous is not None:
            raise DuplicateModuleError(f"Module {name!r} maps to both {previous} and {path}")
        seen[name] = path
        modules.append(ModuleRecord(name=name, group=group_for_path(path, source_root), path=path))
    return tuple(sorted(modules, key=_module_sort_key))


def _render_page(group: str, modules: Iterable[ModuleRecord]) -> str:
    title = GROUP_TITLES[group]
    lines = [
        f"# Python API: {title}",
        "",
        GENERATED_HEADER,
        "",
        f"This page indexes every source module in the **{title.lower()}** group. "
        "It is an implementation reference, not a promise that every indexed module or member "
        "is a stable public API.",
        "",
    ]
    for module in modules:
        lines.extend((f"::: {module.name}", ""))
    return "\n".join(lines)


def render_pages(modules: Iterable[ModuleRecord]) -> dict[str, str]:
    """Render one generated Markdown page for each fixed source group."""
    grouped = {group: [] for group in GROUPS}
    for module in modules:
        if module.group not in grouped:
            raise UnexpectedSourceGroupError(f"Unknown generated group: {module.group}")
        grouped[module.group].append(module)

    return {
        f"{group}.md": _render_page(group, sorted(grouped[group], key=_module_sort_key))
        for group in GROUPS
    }


def _expected_paths(output_root: Path, pages: dict[str, str]) -> dict[str, Path]:
    return {name: output_root / name for name in pages}


def find_output_problems(output_root: Path, pages: dict[str, str]) -> tuple[str, ...]:
    """Return missing, stale, or unexpected generated-page diagnostics."""
    expected = _expected_paths(output_root, pages)
    problems: list[str] = []
    for name, path in expected.items():
        if not path.is_file():
            problems.append(f"missing generated page: {path}")
        elif path.read_text(encoding="utf-8") != pages[name]:
            problems.append(f"stale generated page: {path}")

    actual = {path.name for path in output_root.glob("*.md")} if output_root.is_dir() else set()
    for name in sorted(actual - expected.keys()):
        problems.append(f"unexpected generated page: {output_root / name}")
    return tuple(problems)


def _write_atomically(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    temporary_path = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        os.replace(temporary_path, path)
    except BaseException:
        temporary_path.unlink(missing_ok=True)
        raise


def write_pages(output_root: Path, pages: dict[str, str]) -> None:
    """Publish generated pages without removing unrelated files."""
    for name, content in pages.items():
        path = output_root / name
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            _write_atomically(path, content)


def _parse_args(arguments: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if generated pages are missing, stale, or unexpected",
    )
    return parser.parse_args(arguments)


def main(arguments: Sequence[str] | None = None) -> int:
    """Generate or validate the checked-in API declaration pages."""
    options = _parse_args(arguments)
    modules = discover_modules()
    pages = render_pages(modules)
    problems = find_output_problems(OUTPUT_ROOT, pages)
    if options.check:
        if problems:
            for problem in problems:
                print(problem)
            return 1
        print(f"API reference is current: {len(modules)} modules in {len(pages)} pages.")
        return 0

    write_pages(OUTPUT_ROOT, pages)
    print(f"Generated API reference: {len(modules)} modules in {len(pages)} pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
